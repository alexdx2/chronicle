// BootstrapInput says which repository gets a manifest and what it is called.
type BootstrapInput struct {
	// RepoRoot is the git repository; the manifest lives in <RepoRoot>/.depbot.
	RepoRoot string
	// ProjectPath is the GitLab project path (e.g. "platform/billing"); empty
	// means the base name of RepoRoot.
	ProjectPath string
}

// BootstrapResult describes the manifest that is now on disk.
type BootstrapResult struct {
	Path    string
	Created bool
	// Domain is the domain key (for an existing manifest, its first domain).
	Domain string
	// Tech is the manifest's tech list, created or existing.
	Tech []string
}

// DomainKey normalizes a project path into a domain key: lower-case ASCII
// letters and digits, every other run of characters collapsed to one "-",
// no leading or trailing "-". Nothing left means "repo".
func DomainKey(projectPath string) string {
	var b strings.Builder
	dash := false
	for _, r := range strings.ToLower(projectPath) {
		if (r >= 'a' && r <= 'z') || (r >= '0' && r <= '9') {
			if dash && b.Len() > 0 {
				b.WriteByte('-')
			}
			dash = false
			b.WriteRune(r)
		} else {
			dash = true
		}
	}
	if b.Len() == 0 {
		return "repo"
	}
	return b.String()
}

// bootstrapExclude are the only exclusions a bootstrap manifest carries.
var bootstrapExclude = []string{"**/node_modules/**", "**/vendor/**", "**/dist/**", "**/generated/**"}

// bootstrapSourceExts are the source extensions that earn an include glob.
var bootstrapSourceExts = []string{
	".cjs", ".cs", ".go", ".gql", ".graphql", ".java", ".js", ".jsx", ".kt",
	".mjs", ".php", ".prisma", ".proto", ".py", ".rb", ".rs", ".ts", ".tsx",
}

// maxPackageJSON bounds how much of one package.json is read.
const maxPackageJSON = 256 << 10

const bootstrapTemplate = `# Generated by chronicle scan --full (deterministic bootstrap). Edit freely: an existing manifest is never overwritten.
domains:
  {{.Key}}:
    name: {{.Name}}
    scan:
{{- if .Include}}
      include:
{{- range .Include}}
        - "{{.}}"
{{- end}}
{{- end}}
      exclude:
{{- range .Exclude}}
        - "{{.}}"
{{- end}}
tech: [{{join .Tech ", "}}]
`

var bootstrapTmpl = template.Must(template.New("bootstrap").Funcs(template.FuncMap{"join": strings.Join}).Parse(bootstrapTemplate))

// BootstrapManifest makes sure the repository has a chronicle.domain.yaml. An
// existing manifest is never modified: a valid one is reported as is, an
// invalid one is an error. A missing one is generated from the tracked files
// alone, so the same commit always yields the same bytes.
func BootstrapManifest(in BootstrapInput) (BootstrapResult, error) {
	mpath := filepath.Join(in.RepoRoot, ".depbot", "chronicle.domain.yaml")

	if _, err := os.Stat(mpath); err == nil {
		return loadExisting(mpath)
	} else if !errors.Is(err, os.ErrNotExist) {
		return BootstrapResult{}, fmt.Errorf("scan: stat manifest %s: %w", mpath, err)
	}

	out, err := gitutil.RunRaw(in.RepoRoot, "ls-files", "-z")
	if err != nil {
		return BootstrapResult{}, fmt.Errorf("scan: list tracked files in %s: %w", in.RepoRoot, err)
	}
	var files []string
	for _, f := range strings.Split(out, "\x00") {
		if f != "" {
			files = append(files, f)
		}
	}

	pp := in.ProjectPath
	if pp == "" {
		pp = filepath.Base(filepath.Clean(in.RepoRoot))
	}
	key := DomainKey(pp)
	include, tech := classify(in.RepoRoot, files)

	var buf bytes.Buffer
	// ScanConfigFor matches domains by name, so the name is the normalized key,
	// not the raw project path.
	err = bootstrapTmpl.Execute(&buf, map[string]any{
		"Key":     key,
		"Name":    key,
		"Include": include,
		"Exclude": bootstrapExclude,
		"Tech":    tech,
	})
	if err != nil {
		return BootstrapResult{}, fmt.Errorf("scan: render manifest: %w", err)
	}

	dir := filepath.Dir(mpath)
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return BootstrapResult{}, fmt.Errorf("scan: create %s: %w", dir, err)
	}
	tmp, err := os.CreateTemp(dir, ".chronicle.domain.yaml.*")
	if err != nil {
		return BootstrapResult{}, fmt.Errorf("scan: write manifest: %w", err)
	}
	defer os.Remove(tmp.Name()) // no-op after a successful rename
	if _, err := tmp.Write(buf.Bytes()); err != nil {
		tmp.Close()
		return BootstrapResult{}, fmt.Errorf("scan: write manifest: %w", err)
	}
	if err := tmp.Close(); err != nil {
		return BootstrapResult{}, fmt.Errorf("scan: write manifest: %w", err)
	}
	if err := os.Chmod(tmp.Name(), 0o644); err != nil {
		return BootstrapResult{}, fmt.Errorf("scan: write manifest: %w", err)
	}
	if err := os.Rename(tmp.Name(), mpath); err != nil {
		return BootstrapResult{}, fmt.Errorf("scan: install manifest %s: %w", mpath, err)
	}
	return BootstrapResult{Path: mpath, Created: true, Domain: key, Tech: tech}, nil
}

func loadExisting(mpath string) (BootstrapResult, error) {
	m, err := manifest.LoadFile(mpath)
	if err != nil {
		return BootstrapResult{}, fmt.Errorf("scan: existing manifest %s is invalid, not overwriting: %w", mpath, err)
	}
	return BootstrapResult{Path: mpath, Domain: m.Domains[0].Key, Tech: m.Tech}, nil
}

// classify derives the include globs and the tech list from tracked files.
func classify(repoRoot string, files []string) (include, tech []string) {
	exts := map[string]bool{}
	hasBase := map[string]bool{}
	var pkgJSONs []string
	hasCompose := map[string]bool{} // ".yml" / ".yaml"
	for _, f := range files {
		base := path.Base(f)
		ext := strings.ToLower(path.Ext(base))
		exts[ext] = true
		hasBase[base] = true
		if strings.HasPrefix(base, "docker-compose") && (ext == ".yml" || ext == ".yaml") {
			hasCompose[ext] = true
		}
		if base == "package.json" && !matchesAny(f, bootstrapExclude) {
			pkgJSONs = append(pkgJSONs, f)
		}
	}

	for _, e := range bootstrapSourceExts { // already alphabetical
		if exts[e] {
			include = append(include, "**/*"+e)
		}
	}
	// Build and deployment files, in byte order of the glob.
	for _, b := range []struct {
		glob string
		has  bool
	}{
		{"**/*.csproj", exts[".csproj"]},
		{"**/Dockerfile", hasBase["Dockerfile"]},
		{"**/docker-compose*.yaml", hasCompose[".yaml"]},
		{"**/docker-compose*.yml", hasCompose[".yml"]},
		{"**/go.mod", hasBase["go.mod"]},
		{"**/package.json", hasBase["package.json"]},
	} {
		if b.has {
			include = append(include, b.glob)
		}
	}

	var nest, prismaClient, graphqlDep, kafka bool
	for _, p := range pkgJSONs {
		body := readCapped(filepath.Join(repoRoot, filepath.FromSlash(p)))
		nest = nest || strings.Contains(body, `"@nestjs/`)
		prismaClient = prismaClient || strings.Contains(body, `"@prisma/client"`)
		graphqlDep = graphqlDep || strings.Contains(body, `"graphql"`)
		kafka = kafka || strings.Contains(body, `"kafkajs"`)
	}

	hasPkg := hasBase["package.json"]
	if hasPkg || exts[".ts"] || exts[".tsx"] || exts[".js"] || exts[".jsx"] || exts[".mjs"] || exts[".cjs"] {
		tech = append(tech, "typescript")
	}
	if nest {
		tech = append(tech, "nestjs")
	}
	if hasBase["schema.prisma"] || prismaClient {
		tech = append(tech, "prisma")
	}
	if exts[".graphql"] || exts[".gql"] || graphqlDep {
		tech = append(tech, "graphql")
	}
	if exts[".csproj"] || exts[".sln"] {
		tech = append(tech, "dotnet")
	}
	if kafka {
		tech = append(tech, "kafka")
	}
	return include, tech
}

func matchesAny(p string, globs []string) bool {
	for _, g := range globs {
		if manifest.MatchGlob(p, g) {
			return true
		}
	}
	return false
}

// readCapped reads at most maxPackageJSON bytes; an unreadable file is empty.
func readCapped(p string) string {
	f, err := os.Open(p)
	if err != nil {
		return ""
	}
	defer f.Close()
	b, _ := io.ReadAll(io.LimitReader(f, maxPackageJSON))
	return string(b)
}
