// newCodeRepoT is a plain committed repository (the "code repo" of BuildInput),
// with no store and no project root involved.
func newCodeRepoT(t *testing.T, files map[string]string) (root, head string) {
	t.Helper()
	root = t.TempDir()
	gitT(t, root, "init", "-q", "-b", "main")
	gitT(t, root, "config", "user.email", "t@example.com")
	gitT(t, root, "config", "user.name", "t")
	gitT(t, root, "config", "commit.gpgsign", "false")
	for rel, content := range files {
		writeT(t, root, rel, content)
	}
	return root, commitAllT(t, root, "c1")
}

// worktrees lists the working copies git knows about for repo.
func worktrees(t *testing.T, repo string) []string {
	t.Helper()
	var out []string
	for _, l := range strings.Split(gitT(t, repo, "worktree", "list", "--porcelain"), "\n") {
		if strings.HasPrefix(l, "worktree ") {
			out = append(out, strings.TrimPrefix(l, "worktree "))
		}
	}
	return out
}

func buildIn(repo, sha, workDir string, b llm.Backend) BuildInput {
	return BuildInput{Repo: "proj", CodeRepo: repo, Sha: sha, WorkDir: workDir, Backend: b, Concurrency: 1}
}

func decodeT(t *testing.T, f snapshot.Files) *snapshot.Snapshot {
	t.Helper()
	s, _, err := snapshot.Decode(bytes.NewReader(f.Graph), snapshot.DefaultLimits())
	if err != nil {
		t.Fatal(err)
	}
	return s
}

func blobOf(s *snapshot.Snapshot, path string) string {
	for _, c := range s.Coverage {
		if c.Path == path {
			return c.Blob
		}
	}
	return ""
}

func assertNoWorkingCopies(t *testing.T, repo, workDir string) {
	t.Helper()
	if wts := worktrees(t, repo); len(wts) != 1 {
		t.Fatalf("worktrees after build = %v, want only the main one", wts)
	}
	left, err := os.ReadDir(workDir)
	if err != nil {
		t.Fatal(err)
	}
	if len(left) != 0 {
		t.Fatalf("work dir not empty after build: %v", left)
	}
}

func TestBuildSnapshot_FullFromScratch(t *testing.T) {
	repo, c1 := newCodeRepoT(t, fiveFiles())
	work := t.TempDir()
	b := &countingBackend{}
	res, err := BuildSnapshot(context.Background(), buildIn(repo, c1, work, b))
	if err != nil {
		t.Fatal(err)
	}
	if res.Incremental || res.BaseSha != "" || res.CodeSha != c1 {
		t.Fatalf("result = %+v", res)
	}
	if len(res.Files.Graph) == 0 || len(res.Files.Domain) == 0 {
		t.Fatalf("empty files: graph %d domain %d", len(res.Files.Graph), len(res.Files.Domain))
	}
	if id, _ := res.Files.ContentID(); id == "" || id != res.SnapshotID {
		t.Fatalf("SnapshotID %q != ContentID %q", res.SnapshotID, id)
	}
	if !strings.Contains(string(res.Files.Domain), "Generated by chronicle scan --full") {
		t.Fatalf("domain is not the generated manifest:\n%s", res.Files.Domain)
	}
	if res.ChangedFiles != 5 || b.total() != 5 || res.Partial || len(res.Failed) != 0 {
		t.Fatalf("changed %d, calls %d, partial %v, failed %v", res.ChangedFiles, b.total(), res.Partial, res.Failed)
	}
	if len(res.Metrics) != 5 {
		t.Fatalf("metrics = %d, want 5", len(res.Metrics))
	}
	assertNoWorkingCopies(t, repo, work)
}

// twoCommits builds C1 (five files) fully, then commits C2: f2 edited, f6 added,
// f3 deleted.
func twoCommits(t *testing.T) (repo, c1, c2 string, first *BuildResult) {
	t.Helper()
	repo, c1 = newCodeRepoT(t, fiveFiles())
	first, err := BuildSnapshot(context.Background(), buildIn(repo, c1, t.TempDir(), &countingBackend{}))
	if err != nil {
		t.Fatal(err)
	}
	writeT(t, repo, "src/f2.ts", "export const f2 = 22;\n")
	writeT(t, repo, "src/f6.ts", "export const f6 = 6;\n")
	if err := os.Remove(repo + "/src/f3.ts"); err != nil {
		t.Fatal(err)
	}
	c2 = commitAllT(t, repo, "c2")
	return repo, c1, c2, first
}

func TestBuildSnapshot_IncrementalSendsOnlyChangedFiles(t *testing.T) {
	repo, c1, c2, first := twoCommits(t)
	work := t.TempDir()
	b := &countingBackend{}
	in := buildIn(repo, c2, work, b)
	in.Base = &Base{CodeSha: c1, Files: first.Files}
	res, err := BuildSnapshot(context.Background(), in)
	if err != nil {
		t.Fatal(err)
	}
	if !res.Incremental || res.BaseSha != c1 || res.ChangedFiles != 2 || b.total() != 2 {
		t.Fatalf("incremental %v base %s changed %d calls %d", res.Incremental, res.BaseSha, res.ChangedFiles, b.total())
	}
	if b.callsFor("src/f2.ts") != 1 || b.callsFor("src/f6.ts") != 1 {
		t.Fatalf("calls = %v", b.calls)
	}
	was, now := decodeT(t, first.Files), decodeT(t, res.Files)
	if blobOf(was, "src/f1.ts") == "" || blobOf(now, "src/f1.ts") != blobOf(was, "src/f1.ts") {
		t.Fatalf("f1 coverage blob %q -> %q", blobOf(was, "src/f1.ts"), blobOf(now, "src/f1.ts"))
	}
	if blobOf(now, "src/f2.ts") == blobOf(was, "src/f2.ts") || blobOf(now, "src/f6.ts") == "" {
		t.Fatalf("f2 %q -> %q, f6 %q", blobOf(was, "src/f2.ts"), blobOf(now, "src/f2.ts"), blobOf(now, "src/f6.ts"))
	}
	// Known gap, not asserted: nothing in the store drops the coverage row of a
	// deleted file (chronicle refresh leaves it too), so f3 keeps its old row.
	if now.Header.Seq != was.Header.Seq+1 {
		t.Fatalf("seq %d -> %d, want +1", was.Header.Seq, now.Header.Seq)
	}
	assertNoWorkingCopies(t, repo, work)
}

