func TestBuildSnapshot_BaseNotAnAncestorStillWorks(t *testing.T) {
	repo, c1 := newCodeRepoT(t, fiveFiles())
	first, err := BuildSnapshot(context.Background(), buildIn(repo, c1, t.TempDir(), &countingBackend{}))
	if err != nil {
		t.Fatal(err)
	}
	gitT(t, repo, "checkout", "-q", "-b", "side")
	writeT(t, repo, "src/f1.ts", "export const f1 = 100;\n")
	side := commitAllT(t, repo, "side")
	sideSnap, err := BuildSnapshot(context.Background(), buildIn(repo, side, t.TempDir(), &countingBackend{}))
	if err != nil {
		t.Fatal(err)
	}
	gitT(t, repo, "checkout", "-q", "main")
	writeT(t, repo, "src/f2.ts", "export const f2 = 200;\n")
	main2 := commitAllT(t, repo, "main2")
	_ = first

	b := &countingBackend{}
	in := buildIn(repo, main2, t.TempDir(), b)
	in.Base = &Base{CodeSha: side, Files: sideSnap.Files}
	res, err := BuildSnapshot(context.Background(), in)
	if err != nil {
		t.Fatal(err)
	}
	// git diff side..main2: f1 (side's edit reverted) and f2.
	if !res.Incremental || res.ChangedFiles != 2 || b.callsFor("src/f1.ts") != 1 || b.callsFor("src/f2.ts") != 1 {
		t.Fatalf("incremental %v changed %d calls %v", res.Incremental, res.ChangedFiles, b.calls)
	}
	now := decodeT(t, res.Files)
	wantBlob := gitT(t, repo, "rev-parse", main2+":src/f1.ts")
	if blobOf(now, "src/f1.ts") != wantBlob {
		t.Fatalf("f1 blob %q, want %q", blobOf(now, "src/f1.ts"), wantBlob)
	}
}

const publishersManifest = "domains:\n  proj:\n    name: proj\n    scan:\n      include: [\"src/**\"]\ntech: [typescript]\npublishers:\n  allowed_signers: |\n    ops@example.com ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIOMqqnkVzrm0SdG6UOoqKl1ubTTLN2jhrxKpFqrnPSVN\n"
const treeManifest = "domains:\n  proj:\n    name: proj\n    scan:\n      include: [\"src/**\"]\ntech: [typescript]\n# from the tree\n"

func TestBuildSnapshot_ManifestPrecedence(t *testing.T) {
	// A base to carry: built on a repo with the publishers manifest.
	baseRepo, b1 := newCodeRepoT(t, mergeFiles(fiveFiles(), map[string]string{".depbot/chronicle.domain.yaml": publishersManifest}))
	baseSnap, err := BuildSnapshot(context.Background(), buildIn(baseRepo, b1, t.TempDir(), &countingBackend{}))
	if err != nil {
		t.Fatal(err)
	}
	if string(baseSnap.Files.Domain) != publishersManifest {
		t.Fatalf("setup: base manifest = %q", baseSnap.Files.Domain)
	}

	// (a) the tree has its own manifest: it wins over the base's.
	repoA, a1 := newCodeRepoT(t, mergeFiles(fiveFiles(), map[string]string{".depbot/chronicle.domain.yaml": treeManifest}))
	in := buildIn(repoA, a1, t.TempDir(), &countingBackend{})
	in.Base = &Base{CodeSha: b1, Files: baseSnap.Files} // b1 is not in repoA: full scan, tree manifest
	resA, err := BuildSnapshot(context.Background(), in)
	if err != nil {
		t.Fatal(err)
	}
	if string(resA.Files.Domain) != treeManifest {
		t.Fatalf("(a) Domain = %q, want the tree's", resA.Files.Domain)
	}

	// (a') same with a real base present in the repo.
	fullA, err := BuildSnapshot(context.Background(), buildIn(repoA, a1, t.TempDir(), &countingBackend{}))
	if err != nil {
		t.Fatal(err)
	}
	writeT(t, repoA, "src/f1.ts", "export const f1 = 11;\n")
	a2 := commitAllT(t, repoA, "a2")
	in = buildIn(repoA, a2, t.TempDir(), &countingBackend{})
	other := fullA.Files
	other.Domain = []byte(publishersManifest)
	in.Base = &Base{CodeSha: a1, Files: other}
	resA2, err := BuildSnapshot(context.Background(), in)
	if err != nil {
		t.Fatal(err)
	}
	if !resA2.Incremental || string(resA2.Files.Domain) != treeManifest {
		t.Fatalf("(a') incremental %v Domain %q", resA2.Incremental, resA2.Files.Domain)
	}

	// (b) no manifest in the tree, base has one with publishers: byte for byte.
	repoB, c1 := newCodeRepoT(t, fiveFiles())
	baseB, err := BuildSnapshot(context.Background(), buildIn(repoB, c1, t.TempDir(), &countingBackend{}))
	if err != nil {
		t.Fatal(err)
	}
	writeT(t, repoB, "src/f1.ts", "export const f1 = 11;\n")
	c2 := commitAllT(t, repoB, "c2")
	filesB := baseB.Files
	filesB.Domain = []byte(string(baseB.Files.Domain) + "publishers:\n  allowed_signers: |\n    ops@example.com ssh-ed25519 AAAAC3NzaC1lZDI1NTE5AAAAIOMqqnkVzrm0SdG6UOoqKl1ubTTLN2jhrxKpFqrnPSVN\n")
	in = buildIn(repoB, c2, t.TempDir(), &countingBackend{})
	in.Base = &Base{CodeSha: c1, Files: filesB}
	resB, err := BuildSnapshot(context.Background(), in)
	if err != nil {
		t.Fatal(err)
	}
	if !resB.Incremental || !bytes.Equal(resB.Files.Domain, filesB.Domain) {
		t.Fatalf("(b) incremental %v Domain:\n%s\nwant:\n%s", resB.Incremental, resB.Files.Domain, filesB.Domain)
	}

	// (c) nowhere: generated (covered by FullFromScratch); the inputs are untouched.
	if string(baseSnap.Files.Domain) != publishersManifest {
		t.Fatal("base files were modified")
	}
	if got, _ := os.ReadFile(repoA + "/.depbot/chronicle.domain.yaml"); string(got) != treeManifest {
		t.Fatalf("code repo manifest changed: %q", got)
	}
	if gitT(t, repoA, "status", "--porcelain") != "" {
		t.Fatalf("code repo dirty: %s", gitT(t, repoA, "status", "--porcelain"))
	}
}

func mergeFiles(a, b map[string]string) map[string]string {
	out := map[string]string{}
	for k, v := range a {
		out[k] = v
	}
	for k, v := range b {
		out[k] = v
	}
	return out
}

func TestBuildSnapshot_CancelledCleansUp(t *testing.T) {
	repo, c1 := newCodeRepoT(t, fiveFiles())
	work := t.TempDir()
	ctx, cancel := context.WithCancel(context.Background())
	defer cancel()
	b := &countingBackend{cancelAfter: 2, cancel: cancel}
	res, err := BuildSnapshot(ctx, buildIn(repo, c1, work, b))
	if !errors.Is(err, context.Canceled) {
		t.Fatalf("err = %v, want context.Canceled", err)
	}
	if res == nil {
		t.Fatal("a cancelled build still returns its partial result")
	}
	assertNoWorkingCopies(t, repo, work)
}

// hookBackend records the highest number of Complete calls in flight across
// every build that shares it.
type hookBackend struct {
	inner *countingBackend
	mu    sync.Mutex
	now   int
	max   int
}

func (h *hookBackend) Name() string  { return "fake" }
func (h *hookBackend) Model() string { return "fake" }
func (h *hookBackend) Complete(ctx context.Context, req llm.Request) (llm.Response, error) {
	h.mu.Lock()
	h.now++
	if h.now > h.max {
		h.max = h.now
	}
	h.mu.Unlock()
	defer func() { h.mu.Lock(); h.now--; h.mu.Unlock() }()
	return h.inner.Complete(ctx, req)
}

func TestBuildSnapshot_ProcessWideStateRestoredAndSerialised(t *testing.T) {
	repo1, s1 := newCodeRepoT(t, fiveFiles())
	repo2, s2 := newCodeRepoT(t, fiveFiles())
	paths.SetProjectRoot("/sentinel")
	paths.SetChronicleDir(".sentinel-dir")
	t.Cleanup(func() { paths.SetProjectRoot(""); paths.SetChronicleDir("") })

	h := &hookBackend{inner: &countingBackend{}}
	var wg sync.WaitGroup
	errs := make([]error, 2)
	for i, c := range []struct{ repo, sha string }{{repo1, s1}, {repo2, s2}} {
		wg.Add(1)
		go func() {
			defer wg.Done()
			_, errs[i] = BuildSnapshot(context.Background(), buildIn(c.repo, c.sha, t.TempDir(), h))
		}()
	}
	wg.Wait()
	for _, err := range errs {
		if err != nil {
			t.Fatal(err)
		}
	}
	if paths.Root() != "/sentinel" || paths.ConfiguredDir() != ".sentinel-dir" {
		t.Fatalf("process state not restored: root %q dir %q", paths.Root(), paths.ConfiguredDir())
	}
	if h.max != 1 {
		t.Fatalf("max concurrent model calls = %d, want 1 (builds serialised, Concurrency 1)", h.max)
	}
}

// captureStore remembers the PutOptions of every Put.
type captureStore struct {
	*snapshot.MemStore
	puts []snapshot.PutOptions
}

func (c *captureStore) Put(ctx context.Context, repo, sha string, f snapshot.Files, o snapshot.PutOptions) (snapshot.PutResult, error) {
	c.puts = append(c.puts, o)
	return c.MemStore.Put(ctx, repo, sha, f, o)
}

func TestBuildWithStore_UsesNearestAncestorAsBase(t *testing.T) {
	repo, c1 := newCodeRepoT(t, fiveFiles())
	st := &captureStore{MemStore: snapshot.NewMemStore()}
	ctx := context.Background()
	b1 := &countingBackend{}
	pr, res, err := BuildWithStore(ctx, st, buildIn(repo, c1, t.TempDir(), b1), StoreBuildOptions{})
	if err != nil || !pr.Created || res == nil || res.Incremental {
		t.Fatalf("first: %+v %+v %v", pr, res, err)
	}
	snapC1 := pr.Entry.SnapshotID

	writeT(t, repo, "src/f1.ts", "export const f1 = 11;\n")
	commitAllT(t, repo, "c2")
	writeT(t, repo, "src/f2.ts", "export const f2 = 22;\n")
	c3 := commitAllT(t, repo, "c3")
	b3 := &countingBackend{}
	pr, res, err = BuildWithStore(ctx, st, buildIn(repo, c3, t.TempDir(), b3), StoreBuildOptions{})
	if err != nil || !pr.Created {
		t.Fatalf("second: %+v %v", pr, err)
	}
	if res.BaseSha != c1 || pr.Entry.CodeSha != c3 || b3.total() != 2 {
		t.Fatalf("base %q entry %q calls %d", res.BaseSha, pr.Entry.CodeSha, b3.total())
	}
	if got := st.puts[len(st.puts)-1].Base; got != snapC1 {
		t.Fatalf("PutOptions.Base = %q, want %q", got, snapC1)
	}

	b4 := &countingBackend{}
	pr, res, err = BuildWithStore(ctx, st, buildIn(repo, c3, t.TempDir(), b4), StoreBuildOptions{})
	if err != nil || pr.Created || res != nil || b4.total() != 0 || pr.Entry.CodeSha != c3 {
		t.Fatalf("repeat: %+v %+v %v calls %d", pr, res, err, b4.total())
	}
}

func TestBuildWithStore_FailedFilesAreNotPutUnlessPartialAllowed(t *testing.T) {
	repo, c1 := newCodeRepoT(t, fiveFiles())
	st := &captureStore{MemStore: snapshot.NewMemStore()}
	ctx := context.Background()
	b := &countingBackend{failPaths: map[string]bool{"src/f2.ts": true}}

	pr, res, err := BuildWithStore(ctx, st, buildIn(repo, c1, t.TempDir(), b), StoreBuildOptions{})
	if !errors.Is(err, ErrIncomplete) {
		t.Fatalf("err = %v, want ErrIncomplete", err)
	}
	if res == nil || len(res.Failed) != 1 || !res.Partial || pr.Created {
		t.Fatalf("res %+v put %+v", res, pr)
	}
	if len(st.puts) != 0 {
		t.Fatalf("a partial snapshot was put: %v", st.puts)
	}
	if list, _ := st.List(ctx, "proj"); len(list) != 0 {
		t.Fatalf("store holds %v", list)
	}

	in := buildIn(repo, c1, t.TempDir(), b)
	in.AllowPartial = true
	pr, res, err = BuildWithStore(ctx, st, in, StoreBuildOptions{})
	if err != nil || !pr.Created || !res.Partial || len(st.puts) != 1 {
		t.Fatalf("allow partial: %+v %+v %v puts %d", pr, res, err, len(st.puts))
	}
}
