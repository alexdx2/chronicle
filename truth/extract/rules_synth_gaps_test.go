func keysOf(t *testing.T, files map[string]string, class truth.Class) string {
	t.Helper()
	m := fstest.MapFS{}
	for p, c := range files {
		m[p] = &fstest.MapFile{Data: []byte(c)}
	}
	rep, err := Extract(m)
	if err != nil {
		t.Fatal(err)
	}
	var out []string
	for _, f := range rep.Facts {
		if f.Class == class {
			out = append(out, f.Key)
		}
	}
	sort.Strings(out)
	return strings.Join(out, ",")
}

func TestAppSettingsAnyKeyURL(t *testing.T) {
	cases := []struct{ name, json, want string }{
		{"any key", `{"Services": {"PricingApi": "http://pricing-api:8080"}}`, "pricing-api"},
		{"https and url key", `{"A": {"Foo": "https://a.example.com/x", "NotifyUrl": "http://notify-svc:3000"}}`, "a.example.com,notify-svc"},
		{"kestrel and localhost", `{"Urls": "http://localhost:5000", "Kestrel": {"Endpoints": {"Http": {"Address": "http://127.0.0.1:5001"}}}}`, ""},
		{"schema url", `{"$schema": "http://json-schema.org/draft-07/schema#", "Meta": {"Spec": "https://json.schemastore.org/appsettings.json"}}`, ""},
		{"doc keys", `{"DocsLink": "https://docs.example.com", "HelpUrl": "https://help.example.com", "SchemaRef": "https://s.example.com"}`, ""},
		{"not a url", `{"Name": "pricing-api", "Conn": "Server=db;Port=5432", "Ftp": "ftp://files.example.com"}`, ""},
	}
	for _, c := range cases {
		if got := keysOf(t, map[string]string{"appsettings.json": c.json}, truth.ClassHTTP); got != c.want {
			t.Errorf("%s: got %q want %q", c.name, got, c.want)
		}
	}
}

func TestTSConfigURL(t *testing.T) {
	env := "export const environment = {\n  production: false,\n  apiUrl: 'http://sales-api:8080',\n  docsUrl: 'https://docs.example.com',\n  local: \"http://localhost:4200\",\n  title: 'portal',\n};\n"
	cases := []struct{ name, path, src, want string }{
		{"environment.ts", "src/environments/environment.ts", env, "sales-api"},
		{"environment.prod.ts", "src/environments/environment.prod.ts", env, "sales-api"},
		{"app.config.ts", "src/app/app.config.ts", "export const cfg = { backend: `https://b.example.com/api` };", "b.example.com"},
		{"other file ignored", "src/app/service.ts", env, ""},
		{"test file ignored", "src/environments/environment.spec.ts", env, ""},
		{"no url", "src/environments/environment.ts", "export const environment = { apiUrl: '/api' };", ""},
	}
	for _, c := range cases {
		if got := keysOf(t, map[string]string{c.path: c.src}, truth.ClassHTTP); got != c.want {
			t.Errorf("%s: got %q want %q", c.name, got, c.want)
		}
	}
}

func TestGeneratedAndExampleCodeExcluded(t *testing.T) {
	route := "import express from 'express';\nconst router = express.Router();\nrouter.get('/demo/hello', (req, res) => res.send('x'));\n"
	call := "fetch('http://other.example.com/x');\n"
	openapi := `{"openapi":"3.0.0","paths":{"/orders":{"get":{}}}}`
	for _, p := range []string{"examples/demo/routes.ts", "example/routes.ts", "pkg/generated/routes.ts", "a/__generated__/routes.ts", "Examples/routes.ts"} {
		if got := keysOf(t, map[string]string{p: route}, truth.ClassEndpoints); got != "" {
			t.Errorf("%s endpoints: %q", p, got)
		}
		if got := keysOf(t, map[string]string{p: call}, truth.ClassHTTP); got != "" {
			t.Errorf("%s http: %q", p, got)
		}
	}
	if got := keysOf(t, map[string]string{"generated/openapi-client/openapi.json": openapi}, truth.ClassEndpoints); got != "" {
		t.Errorf("generated openapi: %q", got)
	}
	// negative: ordinary and look-alike directories still count
	for _, p := range []string{"src/routes.ts", "src/exampled/routes.ts", "src/generator/routes.ts"} {
		if got := keysOf(t, map[string]string{p: route}, truth.ClassEndpoints); got != "GET /demo/hello" {
			t.Errorf("%s endpoints: %q", p, got)
		}
	}
	// header markers
	if got := keysOf(t, map[string]string{"src/gen.ts": "// Code generated by tool. DO NOT EDIT.\n" + route}, truth.ClassEndpoints); got != "" {
		t.Errorf("go-style header: %q", got)
	}
	if got := keysOf(t, map[string]string{"src/Gen.cs": "// <auto-generated>\n//   x\n// </auto-generated>\n" + call}, truth.ClassHTTP); got != "" {
		t.Errorf("cs header: %q", got)
	}
	if got := keysOf(t, map[string]string{"src/ok.ts": "// handwritten, not auto generated\n" + route}, truth.ClassEndpoints); got != "GET /demo/hello" {
		t.Errorf("plain comment: %q", got)
	}
	// deps stay
	lock := keysOf(t, map[string]string{"examples/demo/package.json": `{"name":"d","dependencies":{"left-pad":"1.0.0"}}`}, truth.ClassDeps)
	if !strings.Contains(lock, "left-pad") {
		t.Errorf("deps in examples dropped: %q", lock)
	}
}
