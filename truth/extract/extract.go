package extract

import (
	"fmt"
	"io/fs"
	"path"
	"strings"

	"github.com/alexdx2/chronicle-core/truth"
	"github.com/alexdx2/chronicle-core/truth/extract/lex"
)

func isExcluded(name string) bool {
	for _, e := range Excluded {
		if e == name {
			return true
		}
	}
	return false
}

func silentSkip(name string) bool {
	return strings.HasSuffix(name, ".min.js") || strings.HasSuffix(name, ".map") || strings.HasSuffix(name, ".d.ts")
}

// Extract walks fsys, applies every matching rule and merges the facts.
func Extract(fsys fs.FS) (*truth.Report, error) {
	rep := &truth.Report{RulesVersion: truth.RulesVersion}
	tree := fsTree{fsys}
	var all []truth.Fact
	skipped := map[string]bool{}

	err := fs.WalkDir(fsys, ".", func(p string, d fs.DirEntry, err error) error {
		skipFile := func(e error) error {
			rep.Warnings = append(rep.Warnings, fmt.Sprintf("walk %s: %v", p, e))
			if !skipped[p] {
				skipped[p] = true
				rep.SkippedFiles = append(rep.SkippedFiles, p)
			}
			return nil
		}
		if err != nil {
			if p == "." {
				return err
			}
			if d != nil && d.IsDir() {
				rep.Warnings = append(rep.Warnings, fmt.Sprintf("walk %s: %v", p, err))
				return fs.SkipDir
			}
			return skipFile(err)
		}
		if d.IsDir() {
			if p != "." && isExcluded(d.Name()) {
				return fs.SkipDir
			}
			return nil
		}
		if silentSkip(d.Name()) {
			return nil
		}
		var matched []Rule
		for _, r := range Rules {
			if r.Match(p) {
				matched = append(matched, r)
			}
		}
		if len(matched) == 0 {
			return nil
		}
		info, err := d.Info()
		if err != nil {
			return skipFile(err)
		}
		if info.Size() > MaxFile {
			skipped[p] = true
			rep.SkippedFiles = append(rep.SkippedFiles, p)
			return nil
		}
		raw, err := fs.ReadFile(fsys, p)
		if err != nil {
			return skipFile(err)
		}
		ctx := &FileCtx{
			Path:   p,
			Dir:    path.Dir(p),
			Lines:  lex.Scan(raw, lex.FamilyFor(p)).Lines,
			Raw:    raw,
			IsTest: IsTestPath(p),
			Tree:   tree,
		}
		rep.Files++
		generated := IsGeneratedPath(p) || hasGeneratedHeader(raw)
		for _, r := range matched {
			facts, perr := applySafe(r, ctx)
			if perr != nil {
				rep.Warnings = append(rep.Warnings, fmt.Sprintf("panic in %s on %s: %v", r.Name(), p, perr.v))
				if !skipped[p] {
					skipped[p] = true
					rep.SkippedFiles = append(rep.SkippedFiles, p)
				}
				continue
			}
			if generated {
				facts = keepDepsOnly(facts)
			}
			all = append(all, facts...)
		}
		return nil
	})
	if err != nil {
		return nil, err
	}
	merged, warns := Merge(all)
	rep.Facts = merged
	rep.Warnings = append(rep.Warnings, warns...)
	return rep, nil
}

// generatedDirs hold sample or machine-generated code: not part of the
// repository's own behaviour.
var generatedDirs = map[string]bool{"examples": true, "example": true, "generated": true, "__generated__": true}

// IsGeneratedPath reports whether a directory of p marks example or generated code.
func IsGeneratedPath(p string) bool {
	parts := strings.Split(strings.ReplaceAll(p, "\\", "/"), "/")
	for _, d := range parts[:len(parts)-1] {
		if generatedDirs[strings.ToLower(d)] {
			return true
		}
	}
	return false
}

// hasGeneratedHeader reports a "<auto-generated" or "Code generated ... DO NOT
// EDIT" marker in the first lines of a file.
func hasGeneratedHeader(raw []byte) bool {
	head := raw
	if len(head) > 1024 {
		head = head[:1024]
	}
	lines := strings.SplitN(string(head), "\n", 8)
	if len(lines) > 7 {
		lines = lines[:7]
	}
	for _, l := range lines {
		l = strings.TrimSpace(l)
		if !(strings.HasPrefix(l, "//") || strings.HasPrefix(l, "/*") || strings.HasPrefix(l, "*") || strings.HasPrefix(l, "#")) {
			continue
		}
		if strings.Contains(l, "<auto-generated") ||
			(strings.Contains(l, "Code generated") && strings.Contains(l, "DO NOT EDIT")) {
			return true
		}
	}
	return false
}

// keepDepsOnly drops everything but dependency and package facts: lockfiles
// and manifests keep their meaning inside generated code.
func keepDepsOnly(facts []truth.Fact) []truth.Fact {
	var out []truth.Fact
	for _, f := range facts {
		if f.Class == truth.ClassDeps || f.Class == truth.ClassPackages {
			out = append(out, f)
		}
	}
	return out
}

type panicVal struct{ v any }

func applySafe(r Rule, f *FileCtx) (facts []truth.Fact, pv *panicVal) {
	defer func() {
		if x := recover(); x != nil {
			facts, pv = nil, &panicVal{x}
		}
	}()
	return r.Apply(f), nil
}
